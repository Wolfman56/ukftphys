#!/usr/bin/env python3
"""
Exp 107 post-processing: KZM domain-wall scaling analysis.

Reads 107_exp107_raw.csv (880 rows: L, n_sweeps, rep, dwd)
produced by:
  cargo run --release --features webgpu --example ising_kzm -- exp107

Outputs:
  107_exp107_summary.csv   — mean DWD per (L, n_sweeps)
  107_exp107_results.md    — KZM fit table (exponents + R²)
  107_exp107_plot.png      — log-log scatter + fit lines (optional, requires matplotlib)

Usage:
  python experiments/107_analyze_exp107.py
"""

import csv
import math
import os
from pathlib import Path

HERE = Path(__file__).parent
RAW_CSV   = HERE / "107_exp107_raw.csv"
SUM_CSV   = HERE / "107_exp107_summary.csv"
RESULT_MD = HERE / "107_exp107_results.md"

EXP_THEORY = 1.0 / 3.0   # ν/(1+νz) for 2D model-A Ising


# ─── I/O helpers ────────────────────────────────────────────────────────────

def load_raw(path: Path) -> list[dict]:
    with open(path, newline="") as f:
        reader = csv.DictReader(f)
        return [
            {"L": int(r["L"]), "n_sweeps": int(r["n_sweeps"]),
             "rep": int(r["rep"]), "dwd": float(r["dwd"])}
            for r in reader
        ]


def summarise(rows: list[dict]) -> list[dict]:
    """Compute mean DWD per (L, n_sweeps) pair."""
    groups: dict[tuple, list[float]] = {}
    for r in rows:
        key = (r["L"], r["n_sweeps"])
        groups.setdefault(key, []).append(r["dwd"])
    out = []
    for (L, n), vals in sorted(groups.items()):
        out.append({
            "L": L, "n_sweeps": n,
            "n_reps": len(vals),
            "mean_dwd": sum(vals) / len(vals),
            "std_dwd":  (sum((v - sum(vals)/len(vals))**2 for v in vals) / max(len(vals)-1,1))**0.5,
            "n_nonzero": sum(1 for v in vals if v > 0),
        })
    return out


def save_summary(rows: list[dict], path: Path):
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["L", "n_sweeps", "n_reps", "mean_dwd", "std_dwd", "n_nonzero"])
        w.writeheader()
        w.writerows(rows)
    print(f"Summary saved → {path}")


# ─── KZM fitting ────────────────────────────────────────────────────────────

def fit_kzm(summary: list[dict], L: int) -> dict:
    """
    OLS log-log fit: log(DWD) = alpha + beta * log(n_sweeps)
    Only include rows where mean_dwd > 0.
    Returns dict with 'exponent', 'intercept', 'r2', 'n_points'.
    """
    pts = [(r["n_sweeps"], r["mean_dwd"])
           for r in summary
           if r["L"] == L and r["mean_dwd"] > 0.0]

    if len(pts) < 3:
        return {"exponent": float("nan"), "intercept": float("nan"),
                "r2": 0.0, "n_points": len(pts)}

    xs = [math.log(n) for n, _ in pts]
    ys = [math.log(d) for _, d in pts]
    n  = len(xs)
    mx, my = sum(xs)/n, sum(ys)/n
    sxx = sum((x - mx)**2 for x in xs)
    sxy = sum((x - mx)*(y - my) for x, y in zip(xs, ys))
    syy = sum((y - my)**2 for y in ys)

    if sxx == 0:
        return {"exponent": float("nan"), "intercept": float("nan"),
                "r2": 0.0, "n_points": n}

    beta      = sxy / sxx
    intercept = my - beta * mx
    ss_res    = sum((y - (intercept + beta*x))**2 for x, y in zip(xs, ys))
    r2        = 1.0 - ss_res / syy if syy > 0 else 0.0

    return {"exponent": beta, "intercept": intercept, "r2": r2, "n_points": n}


# ─── Markdown report ─────────────────────────────────────────────────────────

def write_report(fits: dict[int, dict], path: Path):
    lines = [
        "# Exp 107 — KZM Fit Results",
        "",
        f"Theory prediction: exponent = −1/3 = {-EXP_THEORY:.4f}",
        "",
        "| L   | exponent | R²     | n_points | status        |",
        "|-----|----------|--------|----------|---------------|",
    ]
    for L in sorted(fits):
        f = fits[L]
        exp = f["exponent"]
        r2  = f["r2"]
        n   = f["n_points"]
        if math.isnan(exp):
            status = "INSUFFICIENT DATA"
            lines.append(f"| {L:3d} | {'nan':8s} | {'n/a':6s} | {n:8d} | {status} |")
        else:
            ok = -0.50 < exp < -0.20 and r2 > 0.80
            status = "PASS ✓" if ok else "WARN"
            lines.append(f"| {L:3d} | {exp:+.4f} | {r2:.4f} | {n:8d} | {status} |")
    lines += [
        "",
        f"Generated by `107_analyze_exp107.py`",
    ]
    path.write_text("\n".join(lines) + "\n")
    print(f"Report saved → {path}")


# ─── Optional plot ───────────────────────────────────────────────────────────

def try_plot(summary: list[dict], fits: dict[int, dict]):
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        import numpy as np
    except ImportError:
        print("matplotlib not available — skipping plot")
        return

    fig, ax = plt.subplots(figsize=(8, 5))
    colors = {64: "C0", 128: "C1", 256: "C2", 512: "C3"}
    markers = {64: "o", 128: "s", 256: "^", 512: "D"}

    for L in sorted(set(r["L"] for r in summary)):
        pts = [(r["n_sweeps"], r["mean_dwd"])
               for r in summary
               if r["L"] == L and r["mean_dwd"] > 0]
        if not pts:
            continue
        ns, ds = zip(*pts)
        ax.scatter(ns, ds, color=colors.get(L, "C4"),
                   marker=markers.get(L, "o"), label=f"L={L}", zorder=3)

        f = fits.get(L, {})
        if not math.isnan(f.get("exponent", float("nan"))):
            xs = np.logspace(math.log10(min(ns)), math.log10(max(ns)), 50)
            ys = np.exp(f["intercept"]) * xs**f["exponent"]
            ax.plot(xs, ys, color=colors.get(L, "C4"), lw=1.5,
                    label=f"L={L} fit ({f['exponent']:+.3f})")

    # Reference slope −1/3
    ns_ref = np.array([200, 204800])
    mid    = summary[len(summary)//2]
    d_ref  = mid["mean_dwd"] if mid["mean_dwd"] > 0 else 0.01
    n_ref  = mid["n_sweeps"]
    ys_ref = d_ref * (ns_ref / n_ref)**(-EXP_THEORY)
    ax.plot(ns_ref, ys_ref, "k--", lw=1, label=f"theory slope −1/3")

    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_xlabel("n_sweeps (quench duration)")
    ax.set_ylabel("⟨DWD⟩")
    ax.set_title("Exp 107: KZM Domain-Wall Scaling — 2D AF Ising")
    ax.legend(fontsize=8)
    ax.grid(True, which="both", alpha=0.3)

    out = HERE / "107_exp107_plot.png"
    fig.tight_layout()
    fig.savefig(out, dpi=150)
    print(f"Plot saved → {out}")


# ─── Main ────────────────────────────────────────────────────────────────────

def main():
    if not RAW_CSV.exists():
        print(f"ERROR: {RAW_CSV} not found.")
        print("Run: cd noogine && OUT_DIR=.../ukftphys/experiments "
              "cargo run --release --features webgpu --example ising_kzm -- exp107")
        return

    print(f"Loading {RAW_CSV} …")
    rows = load_raw(RAW_CSV)
    print(f"  {len(rows)} rows loaded")

    summary = summarise(rows)
    save_summary(summary, SUM_CSV)

    fits: dict[int, dict] = {}
    print("\n── KZM fit ──────────────────────────────────")
    for L in sorted(set(r["L"] for r in summary)):
        f = fits[L] = fit_kzm(summary, L)
        exp = f["exponent"]
        r2  = f["r2"]
        n   = f["n_points"]
        if math.isnan(exp):
            print(f"  L={L:4d}  exponent=    nan  R²={r2:.4f}  n_pts={n}")
        else:
            flag = "" if -0.50 < exp < -0.20 and r2 > 0.80 else "  ← WARN"
            print(f"  L={L:4d}  exponent={exp:+.4f}  R²={r2:.4f}  n_pts={n}{flag}")
    print(f"  (theory: −{EXP_THEORY:.4f})")

    write_report(fits, RESULT_MD)
    try_plot(summary, fits)


if __name__ == "__main__":
    main()
