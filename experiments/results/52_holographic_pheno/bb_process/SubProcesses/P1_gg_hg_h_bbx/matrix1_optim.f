      SUBROUTINE SMATRIX1(P, RHEL, RCOL, channel, IVEC, ANS, IHEL,
     $  ICOL)
C     
C     Generated by MadGraph5_aMC@NLO v. 3.7.0, 2026-01-05
C     By the MadGraph5_aMC@NLO Development Team
C     Visit launchpad.net/madgraph5 and amcatnlo.web.cern.ch
C     
C     MadGraph5_aMC@NLO for Madevent Version
C     
C     Returns amplitude squared summed/avg over colors
C     and helicities
C     for the point in phase space P(0:3,NEXTERNAL)
C     potentially times multi-channel weight
C     
C     Process: g g > h g HIG<=1 HIW<=1 WEIGHTED<=3 @1
C     *   Decay: h > b b~ HIG<=1 HIW<=1 WEIGHTED<=2
C     
      IMPLICIT NONE
