        JAMP(:,:) = (0D0,0D0)
C       JAMPs contributing to orders ALL_ORDERS=1
        TMP_JAMP(2) = AMP( K,3) - AMP( K,4)   !  used 2 times
        TMP_JAMP(1) = AMP( K,1) +  AMP( K,2)   !  used 2 times
        TMP_JAMP(3) = TMP_JAMP(2) +  TMP_JAMP(1)   !  used 2 times
        JAMP(1,1) = ((0.000000000000000D+00,2.000000000000000D+00)) *TMP
     $  _JAMP(3)
        JAMP(2,1) = ((0.000000000000000D+00,-2.000000000000000D+00)) *TM
     $  P_JAMP(3)

        TS(K) = 0.D0 
        DO M = 1, NAMPSO
          CF_INDEX = 0
          DO I = 1, NCOLOR
            ZTEMP = (0.D0,0.D0)
            DO J = I, NCOLOR
              CF_INDEX = CF_INDEX + 1
              ZTEMP = ZTEMP + CF(CF_INDEX)*JAMP(J,M)
            ENDDO    !  J
            DO N = 1, NAMPSO

              TS(K) = TS(K) + REAL(ZTEMP*DCONJG(JAMP(I,N)))

            ENDDO    !  N
          ENDDO    !  I
        ENDDO    !  M
        TS(K) = TS(K) / DENOM
        if(sde_strat.eq.1) then
        
        IF(SDE_STRAT.EQ.1)THEN
          AMP2(2)=AMP2(2)+AMP( K,2)*DCONJG(AMP( K,2))
          AMP2(3)=AMP2(3)+AMP( K,3)*DCONJG(AMP( K,3))
          AMP2(4)=AMP2(4)+AMP( K,4)*DCONJG(AMP( K,4))
        ENDIF

        endif
        Do I = 1, NCOLOR
          DO M = 1, NAMPSO
            DO N = 1, NAMPSO

              Jamp2(i)=Jamp2(i)+DABS(DBLE(Jamp(i,m)*dconjg(Jamp(i,n))))

            enddo
          enddo
        Enddo
      ENDDO    !  K

      END


